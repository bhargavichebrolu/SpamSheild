"""Describe the loaded model, using its metadata and the saved evaluation reports.

Results are read from the reports generated by the training code, not written by hand.
A missing report is reported as None. The removed words themselves are never included,
because they can include people's surnames.
"""

from __future__ import annotations

import json
from pathlib import Path

from app.config import MAX_INPUT_CHARS, REPORTS_DIR
from app.ml.predict import LoadedModel

SCORE_MEANING = (
    "The sign gives the label: positive is spam, and negative is ham. A larger size means "
    "further from the model's decision boundary. It isn't a probability, or a chance of being correct."
)

LIMITATIONS = (
    "This is a learning and research prototype, not an email security product.",
    "Results come from one dataset whose sources and licence are not verified. Real-world performance is unknown.",
    "Performance fell sharply when trained on one text style and scored on another, so unfamiliar email may be misclassified.",
    "Overall scores are lifted by messages very similar to training data.",
    "Do not use this to block, delete or move email, or to detect phishing, fraud or malware.",
)


def _read_report(path: Path) -> dict | None:
    """Return a report's contents, or None if it's missing or unreadable."""
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def _test_results(report: dict, file_hash: str) -> dict:
    metrics = report["overall_metrics"]
    no_close_match = report["metrics_by_similarity_band"]["0.00_to_0.80"]
    return {
        "split": report["split"],
        "rows": report["rows"],
        "accuracy": metrics["accuracy"],
        "precision_spam": metrics["precision_spam"],
        "recall_spam": metrics["recall_spam"],
        "f1_spam": metrics["f1_spam"],
        "roc_auc": report["roc_auc"],
        "ham_flagged_as_spam": metrics["ham_flagged_as_spam"],
        "spam_missed": metrics["spam_missed"],
        "no_close_training_match": {
            "rows": no_close_match["rows"],
            "f1_spam": no_close_match["metrics"]["f1_spam"],
        },
        "report_matches_loaded_file": report["pipeline_sha256"] == file_hash,
    }


def _cross_style_results(report: dict) -> dict:
    def f1(run: str, style: str) -> float:
        return report["cross_style"][run]["validation_by_style"][style]["metrics"]["f1_spam"]

    removal = report["removal_decision"]["candidate"]
    return {
        "note": report["interpretation_note"],
        "digit_style_to_placeholder_style": {
            "f1_without_word_removal": f1("train_digits_only", "placeholder_only"),
            "f1_with_word_removal": f1(f"train_digits_only_{removal}", "placeholder_only"),
        },
        "placeholder_style_to_digit_style": {
            "f1_without_word_removal": f1("train_placeholder_only", "digits_only"),
            "f1_with_word_removal": f1(f"train_placeholder_only_{removal}", "digits_only"),
        },
    }


def build_model_info(model: LoadedModel, reports_dir: Path = REPORTS_DIR) -> dict:
    """Return everything the model-info endpoint reports."""
    metadata = model.metadata
    test_report = _read_report(reports_dir / "final_test_evaluation.json")
    leakage_report = _read_report(reports_dir / "source_leakage.json")
    return {
        "model_version": metadata["model_version"],
        "model_type": metadata["model"],
        "setting": metadata["setting"],
        "features": metadata["features"],
        "vocabulary_size": metadata["vocabulary_size"],
        "removed_word_count": metadata["removed_words"]["count"],
        "training_rows": metadata["training_rows"],
        "max_input_characters": MAX_INPUT_CHARS,
        "provides_probability": False,
        "score_meaning": SCORE_MEANING,
        "file_sha256": metadata["pipeline_sha256"],
        "model_content_sha256": metadata["model_content_sha256"],
        "test_results": _test_results(test_report, metadata["pipeline_sha256"]) if test_report else None,
        "cross_style_results": _cross_style_results(leakage_report) if leakage_report else None,
        "limitations": list(LIMITATIONS),
    }
