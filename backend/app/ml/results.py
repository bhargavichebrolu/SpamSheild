"""Read saved results, for the website's model comparison and dataset pages.

Every number comes from a report generated by the training code. Reports are only read,
and nothing here needs the model to be loaded. The word lists and vocabulary report are
never read, because their words can include people's surnames.
"""

from __future__ import annotations

import json
from pathlib import Path

from app.config import REPORTS_DIR
from app.ml.model_info import LIMITATIONS
from app.ml.predict import DEFAULT_METADATA_PATH

SPLIT_ORDER = ("train", "validation", "test")
NUMBER_STYLE_ORDER = ("placeholder_only", "digits_only", "neither")


class ResultsUnavailable(Exception):
    """Raised when a saved report can't be used. Its message is safe to show to a user."""


def _read_json(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise ResultsUnavailable(
            f"The saved report {path.name} is missing or unreadable, so these results can't be shown."
        ) from error


def _feature_sets(comparison: dict) -> list[dict]:
    return [
        {
            "features": run["features"],
            "train_rows": run["rows_used"]["train"],
            "validation_rows": run["rows_used"]["validation"],
            "vocabulary_size": run["vocabulary_size"],
            "vectorizer_fit_seconds": run["vectorizer_fit_seconds"],
            "peak_memory_gb": run["peak_memory_gb"],
        }
        for run in comparison["runs"].values()
    ]


def _test_evaluation(report: dict, metadata: dict) -> dict:
    return {
        **report,
        "similarity_bands": [
            {"band": band, **values} for band, values in report["metrics_by_similarity_band"].items()
        ],
        "report_matches_saved_model": report["pipeline_sha256"] == metadata["pipeline_sha256"],
    }


def _source_leakage(report: dict) -> dict:
    return {
        "split_used": report["split_used"],
        "interpretation_note": report["interpretation_note"],
        "marker_removal": [
            {
                "name": run["name"],
                "words_removed": run["words_removed"],
                "vocabulary_size": run["vocabulary_size"],
                "metrics": run["validation"]["metrics"],
                "roc_auc": run["validation"]["roc_auc"],
            }
            for run in report["marker_removal"].values()
        ],
        "cross_style": [
            {
                "name": run["name"],
                "training_style": run["training_style"],
                "training_rows": run["training_rows"],
                "words_removed": run["words_removed"],
                "scores": [
                    {"scored_on": style, **score} for style, score in run["validation_by_style"].items()
                ],
            }
            for run in report["cross_style"].values()
        ],
        "removal_decision": report["removal_decision"],
    }


def build_models_results(
    reports_dir: Path = REPORTS_DIR,
    metadata_path: Path = DEFAULT_METADATA_PATH,
) -> dict:
    """Return the saved model comparison, final evaluation and source-leakage results."""
    comparison = _read_json(reports_dir / "model_comparison.json")
    test_report = _read_json(reports_dir / "final_test_evaluation.json")
    validation_report = _read_json(reports_dir / "final_validation_evaluation.json")
    leakage = _read_json(reports_dir / "source_leakage.json")
    metadata = _read_json(metadata_path)

    try:
        return {
            "final_model": {
                "model_version": metadata["model_version"],
                "model": metadata["model"],
                "setting": metadata["setting"],
                "features": metadata["features"],
                "vocabulary_size": metadata["vocabulary_size"],
                "removed_word_count": metadata["removed_words"]["count"],
                "training_rows": metadata["training_rows"],
                "file_sha256": metadata["pipeline_sha256"],
                "model_content_sha256": metadata["model_content_sha256"],
            },
            "selection": {
                "split_used": comparison["split_used_for_selection"],
                "rule": comparison["selection_rule"],
                "selected": comparison["selected"],
            },
            "feature_sets": _feature_sets(comparison),
            "comparison_runs": [run for group in comparison["runs"].values() for run in group["results"]],
            "validation_evaluation": validation_report,
            "test_evaluation": _test_evaluation(test_report, metadata),
            "source_leakage": _source_leakage(leakage),
            "limitations": list(LIMITATIONS),
        }
    except (KeyError, TypeError) as error:
        raise ResultsUnavailable("A saved report doesn't have the expected contents.") from error


def _text_format(report: dict) -> dict:
    styles = report["number_style"]
    spaced = report["spaced_punctuation_share_by_number_style"]
    return {
        "rows_analysed": report["rows_analysed"],
        "number_styles": [
            {
                "style": style,
                "ham_rows": styles[style]["Ham"]["rows"],
                "spam_rows": styles[style]["Spam"]["rows"],
                "spaced_punctuation_share": spaced[style],
            }
            for style in NUMBER_STYLE_ORDER
            if style in styles
        ],
        "flags": [
            {
                "name": name,
                "ham_rows": values["Ham"]["rows"],
                "ham_share": values["Ham"]["share"],
                "spam_rows": values["Spam"]["rows"],
                "spam_share": values["Spam"]["share"],
            }
            for name, values in report["flags_by_label"].items()
        ],
    }


def _preparation(report: dict) -> dict:
    split = report["split"]
    rows = split["rows"]
    return {
        "cleaning": report["cleaning"],
        "random_seed": split["random_seed"],
        "validation_share": split["validation_share"],
        "test_share": split["test_share"],
        "stratified_by": split["stratified_by"],
        "splits": [
            {
                "split": name,
                "total": rows[name]["total"],
                "ham": rows[name]["Ham"],
                "spam": rows[name]["Spam"],
                "spam_share": rows[name]["spam_share"],
            }
            for name in SPLIT_ORDER
        ],
        "preprocessed_texts_shared_between_splits": report["leakage_checks"][
            "preprocessed_texts_shared_between_splits"
        ],
    }


def build_dataset_results(reports_dir: Path = REPORTS_DIR) -> dict:
    """Return verified aggregate statistics about the dataset. It includes no email text."""
    inspection = _read_json(reports_dir / "dataset_inspection.json")
    text_format = _read_json(reports_dir / "format_analysis.json")
    preparation = _read_json(reports_dir / "data_preparation.json")

    try:
        return {
            "source": {
                "reported_source_url": (
                    "https://www.kaggle.com/datasets/meruvulikith/190k-spam-ham-email-dataset-for-classification"
                ),
                "licence": "Not verified",
                "original_sources": "Not verified",
                "label_accuracy": "Not verified",
                "note": "The raw dataset isn't included in this project or redistributed by it.",
            },
            "file": inspection["file"],
            "structure": inspection["structure"],
            "labels": inspection["labels"],
            "missing_values": inspection["missing_values"],
            "blank_text": inspection["blank_text"],
            "duplicates": inspection["duplicates"],
            "lengths": inspection["lengths"],
            "word_shares": [
                {"word": word, "shares": shares}
                for word, shares in inspection["marker_document_frequency"].items()
            ],
            "text_format": _text_format(text_format),
            "preparation": _preparation(preparation),
        }
    except (KeyError, TypeError) as error:
        raise ResultsUnavailable("A saved report doesn't have the expected contents.") from error
